create table if not exists public.readings (
  id bigint generated by default as identity primary key,
  device_id text not null,
  value numeric not null check (value >= 0 and value <= 100),
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists readings_device_created_idx
  on public.readings (device_id, created_at desc);

alter table public.readings enable row level security;

grant usage on schema public to service_role;
grant all privileges on table public.readings to service_role;
grant usage, select on sequence public.readings_id_seq to service_role;

notify pgrst, 'reload schema';
